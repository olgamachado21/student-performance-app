// Lê o idioma guardado (por omissão português); grava a escolha e reaplica as
// traduções sempre que muda (chamado pelo seletor em Configurações).
function getLanguage() {
  try {
    const saved = localStorage.getItem(I18N_STORAGE_KEY);
    return saved === "en" ? "en" : "pt";
  } catch (_) {
    return "pt";
  }
}

function setLanguage(lang) {
  const normalized = lang === "en" ? "en" : "pt";
  try { localStorage.setItem(I18N_STORAGE_KEY, normalized); } catch (_) { /* localStorage indisponível — só não persiste entre sessões */ }
  applyTranslations();

  // applyTranslations() só troca o texto estático marcado com data-i18n no
  // HTML. O texto gerado dinamicamente por cada pages/*.js (KPIs, tabelas,
  // gráficos, modais já abertos) só é escrito no idioma certo quando a
  // página é (re)carregada — e cada página só corre o seu loader uma vez
  // por sessão (ver PAGE_LOADERS em main.js). Em vez de reescrever todas as
  // páginas para suportar recarregar em segurança (risco de duplicar
  // listeners de eventos), recarrega-se a app inteira: mais simples e
  // garante que tudo fica no novo idioma. Guarda-se primeiro a página atual
  // para a app reabrir exatamente onde a pessoa estava, em vez de voltar
  // sempre ao Início.
  try {
    const activeSection = document.querySelector(".page.active");
    const currentPageName = activeSection ? activeSection.id.replace(/^page-/, "") : null;
    if (currentPageName) sessionStorage.setItem("studentperfomanceRestorePage", currentPageName);
  } catch (_) { /* sessionStorage indisponível — recarrega e volta à página inicial, sem partir nada */ }
  window.location.reload();
}

// Devolve o texto traduzido de "key" no idioma atual; recai em português
// (e depois na própria chave) se faltar uma tradução para não deixar a
// interface em branco.
function t(key) {
  const lang = getLanguage();
  const dict = I18N_DICT[lang] || I18N_DICT.pt;
  if (dict[key] !== undefined) return dict[key];
  if (I18N_DICT.pt[key] !== undefined) return I18N_DICT.pt[key];
  return key;
}

// Percorre "root" (por omissão, todo o documento) e substitui o texto de
// qualquer elemento marcado com data-i18n / data-i18n-placeholder /
// data-i18n-title pelo equivalente no idioma atual. Chamado uma vez no
// arranque (ver o listener no fim deste ficheiro) e sempre que o idioma
// muda, para que a troca seja instantânea em toda a app já carregada.
function applyTranslations(root) {
  const scope = root || document;
  const lang = getLanguage();
  document.documentElement.lang = lang === "en" ? "en-GB" : "pt-PT";
  document.title = t("doc_title");

  scope.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const value = t(el.getAttribute("data-i18n-title"));
    el.setAttribute("title", value);
    if (el.hasAttribute("aria-label")) el.setAttribute("aria-label", value);
  });
}

document.addEventListener("DOMContentLoaded", () => applyTranslations());
